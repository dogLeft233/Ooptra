ConfigurationGroupMerger = Callable[[Any, dict[str, Any]], dict[str, Any]]


class RuntimeControl(Protocol):
    """应用通过公开业务能力实现；维护模块不访问业务私有对象。"""

    async def apply_config(self, revision: str, change: ConfigurationChange) -> RuntimeApplyReport: ...
    async def quiesce(self, job_id: str, deadline: float) -> QuiesceResult: ...
    async def request_exit(self, handoff: HandoffRef) -> ExitResult: ...
    def health(self) -> RuntimeHealth: ...


class Configuration(Protocol):
    def revision(self) -> str: ...
    def apply_latest(self, request_id: str, change: ConfigurationChange) -> ConfigurationResult: ...
    def apply(self, request: ConfigurationRequest) -> ConfigurationResult:
        """基于内容摘要 CAS；同请求同载荷重复返回原回执。线程中调用。"""
        ...
    def result(self, request_id: str) -> ConfigurationResult | None: ...
    def record_application(self, request_id: str, report: RuntimeApplyReport) -> ConfigurationResult: ...

    def save_fields(self, change: ConfigurationChange) -> ConfigurationSaveReceipt:
        """在线程中保存已批准的字段并同步运行字典，不表示组件热应用。

        同一进程内锁涵盖读取、可选纯规则合并、可信文档校验、文件提交与运行同步；
        未保存字段保留运行环境覆盖。与 save_output_volume 共用事务。
        调用方负责字段准入；外部版本检查使用 apply，稀疏命令使用 apply_latest。
        """
        ...

    def save_output_volume(self, volume: OutputVolume) -> VolumeSaveReceipt:
        """同进程串行修补磁盘并同步该运行字段，返回不表示播放已应用。

        此方法含阻塞文件 I/O，异步调用者应在线程执行。文件保留注释、其他值、
        权限及符号链接；共用部署变更许可；便利入口不承诺请求幂等或多文件崩溃事务。
        校验/写入失败抛出异常，文件写入成功前不变更运行字典。
        快捷音量写入遇到其他配置/维护任务持有许可时明确拒绝，避免输出锁与部署锁反序。
        线程启动后，异步拥有者必须观察其完成，不得在取消时假定写入停止。
        """
        ...


class Maintenance(Protocol):
    """现有维护任务的公开门面，查询和持久化事实由此能力唯一拥有。

    同步查询含阻塞磁盘/Git 操作，异步入口应在线程执行。异步变更返回的
    job 只表示准备已受理；phase=complete/rolled_back/failed 才是父进程终态。
    close 等待真实准备线程结束，不把调用者取消视为准备已经停止。
    任务记录具有 revision/owner CAS，同一类型计划重复执行返回原任务。
    """

    token: str
    def set_runtime_control(self, control: RuntimeControl) -> None: ...
    async def plan(self, request: MaintenanceRequest) -> MaintenancePlan: ...
    async def execute(self, plan: MaintenancePlan) -> JobRef: ...
    def job(self, reference: JobRef) -> JobSnapshot | None: ...
    def snapshot(self) -> SystemSnapshot: ...
    @property
    def backups(self) -> BackupArchive: ...

    def status(self, page=1, page_size=50) -> dict: ...
    def preflight(self) -> dict: ...
    def probe_network(self, mirror, channel, **options) -> dict: ...
    async def query(self, kind: str) -> dict: ...
    async def check_update(self, channel=None) -> dict: ...
    async def start_update(self, channel, target_sha, *, confirm_channel_switch=False) -> dict: ...
    async def start_restore(self, backup_id) -> dict: ...
    async def create_backup(self) -> dict: ...
    async def delete_backup(self, backup_id) -> dict: ...
    def preview_cleanup(self) -> dict: ...
    async def apply_cleanup(self, token) -> dict: ...
    async def close(self) -> None: ...


class BackupArchive(Protocol):
    """有界归档与验证恢复；同步阻塞，只在停机后恢复真实部署。"""

    def path(self, backup_id: str) -> Path: ...
    def create(self) -> dict: ...
    def list(self, limit: int | None = 50) -> list[dict]: ...
    def validate(self, backup_id: str, stage: Path) -> list[str]: ...
    def inspect(self, backup_id: str) -> ValidatedRestore: ...
    def restore(self, reference: ValidatedRestore, stopped: StoppedDeployment) -> None: ...
    def delete(self, backup_id: str) -> None: ...


class UpdateTransport(Protocol):
    """官方源确定版本，备用镜像只能下载已核对的提交；阻塞 I/O。"""

    def load_network_settings(self) -> NetworkSettings: ...
    def test_mirror_connection(self, mirror, channel, run_command=None, *, proxy=None) -> dict: ...
    def lookup_official_sha(self, root, channel, deadline, run_command=None, *, settings=None, progress=None) -> str: ...
    def fetch_verified(self, root, channel, trusted_sha, deadline, run_command=None, *, settings=None, progress=None) -> str: ...


class Supervisor(Protocol):
    """同步监督本启动器创建的进程；受管切换与失败回滚归此能力。"""

    def supervise(self, root) -> int: ...
    def confirm_stopped(self, process, job: dict) -> StoppedDeployment: ...
    def switch(self, root: Path, job: dict, stopped: StoppedDeployment | None = None) -> Popen[bytes] | None: ...
    def spawn(self, root, python, marker="", browser_path="") -> Popen[bytes]: ...
    def stop_owned(self, process) -> None: ...
    def healthy(self, process, job, timeout=45) -> bool: ...
    def checkout(self, root, sha) -> None: ...
    def runtime_health(self, status, *, expected_pid=None, update_id=None, expected_python=None, expected_marker=None) -> dict: ...


class StorageScanner(Protocol):
    """有界存储盘点；只生成候选并复核指纹，不跟随目录链接。"""

    def inventory(self, root, backups, job, *, timeout=10) -> tuple[dict[str, int], list[dict]]: ...
    def delete_items(self, root, items) -> None: ...


class CredentialStore(Protocol):
    """部署凭据：保存已解析RSA及允许的账户字段，维护屏障覆盖文件和运行同步。"""
    def save(self, credentials: Mapping[str, Any]) -> list[str]: ...
    async def persist(self, credentials: Mapping[str, Any]) -> list[str]:
        """取消只撤销等待；始终观察已启动的保存，返回不代表平台已经重连。"""
        ...
    def load_private_key(self) -> Any: ...


class PlatformConfiguration(Protocol):
    """平台装配配置快照；返回独立值，不提供运行模块/SDK可变对象。"""
    def snapshot(self) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]: ...
    def load_private_key(self) -> Any: ...
    def login_account(self) -> tuple[str, str]: ...
    async def persist_credentials(self, credentials: Mapping[str, Any]) -> list[str]: ...
