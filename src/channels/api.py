class VoiceBinding(Protocol):
    """账号与音频资源生命周期；SDK对象仅用于装配输入，不通过查询返回。

    bind在owner-loop撤回旧绑定；prepare_output在任何共享传输复用前等待旧会话屏障。
    output用于注入测试/预建音频端口，生产由prepare_output创建并拥有。
    """

    identity: str
    @property
    def output(self) -> Duplex | None: ...
    @output.setter
    def output(self, duplex: Duplex | None) -> None: ...
    @property
    def connected(self) -> bool: ...
    @property
    def cleanup_pending(self) -> bool: ...
    @property
    def channel(self) -> Channel: ...
    @property
    def directory(self) -> PlatformDirectory: ...
    def bind(self, bot: object) -> None: ...
    def attach(self, duplex: Duplex) -> None: ...
    async def prepare_output(self) -> Duplex: ...
    async def drain_retired(self) -> str | None: ...
    def resolve_speaker(self, uid: str) -> str: ...
    def subscribe_presence(self, handler: Callable[[str, str], None]) -> None: ...
    async def close(self) -> None: ...


